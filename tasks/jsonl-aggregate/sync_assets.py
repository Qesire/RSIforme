"""Copy task assets from the canonical CPU example, or --check their equality."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

TASK = Path(__file__).resolve().parent
EXAMPLE = TASK.parents[1] / "examples" / "jsonl_aggregate"
PACKAGE = TASK.parents[1] / "src" / "rsiforme"
BUNDLED_PACKAGE = TASK / "environment" / "rsiforme"
ASSETS = {
    EXAMPLE / "evaluate.py": [TASK / "tests" / "evaluate.py"],
    EXAMPLE / "fixtures" / "baseline" / "solution.py": [
        TASK / "tests" / "baseline.py", TASK / "environment" / "solution.py",
    ],
    EXAMPLE / "fixtures" / "optimized" / "solution.py": [TASK / "solution" / "optimized.py"],
}


def generated_config():
    evaluator_sha = hashlib.sha256((EXAMPLE / "evaluate.py").read_bytes()).hexdigest()
    harness = json.loads((TASK.parents[1] / "configs/upstreams.lock.json").read_text())["execution"]["harness"]
    return f'''# Generated by sync_assets.py. New task/runtime conditions require a new archive.
schema_version = 1
task_id = "jsonl-aggregate-harness-v1"
objective = "reward"
direction = "maximize"
source_paths = ["solution.py"]

[context]
task_revision = "jsonl-Harness-v1"
evaluator_revision = "sha256:{evaluator_sha}"
environment = "CPU smoke; Python image tag python:3.11-slim; baseline recalibrated in each Judge; record resolved image and runtime before production comparisons"

[context.upstream_pins.harness]
repository = "{harness['repository']}"
revision = "{harness['revision']}"
package_path = "{harness['package_path']}"

[harness]
task_id = "jsonl-aggregate"

[[harness.gates]]
metric = "quality_passed"
equals = 1
'''.encode("utf-8")


def expected_assets():
    expected = {}
    for source, destinations in ASSETS.items():
        for destination in destinations:
            expected[destination] = source.read_bytes()
    for source in sorted(PACKAGE.rglob("*.py")):
        if "__pycache__" not in source.parts:
            expected[BUNDLED_PACKAGE / source.relative_to(PACKAGE)] = source.read_bytes()
    expected[TASK / "environment" / "archive-task.toml"] = generated_config()
    return expected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatched = []
    expected = expected_assets()
    for destination, contents in expected.items():
        if args.check:
            if not destination.is_file() or destination.read_bytes() != contents:
                mismatched.append(str(destination.relative_to(TASK)))
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(contents)
    for obsolete in sorted(BUNDLED_PACKAGE.rglob("*.py")):
        if obsolete not in expected:
            if args.check:
                mismatched.append(str(obsolete.relative_to(TASK)) + " (obsolete)")
            else:
                obsolete.unlink()
    if mismatched:
        print("Task assets differ from their canonical sources: " + ", ".join(mismatched), file=sys.stderr)
        return 1
    print("Task assets match their canonical sources." if args.check else "Task assets synchronized.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
